#!/usr/bin/env python3
"""Regenerate engine/romm_sync_engine/platform_extensions.py from Argosy.

Usage: scripts/gen_platform_extensions.py <argosy checkout>

Reads PlatformDefinitions.kt: every PlatformDef(slug, ..., setOf(exts), ...)
and the slugAliases map. Argosy uses the same table to pick the ROM to boot
out of an unpacked folder, so mirroring it keeps the two clients agreeing on
which file in a download is the game.
"""
import re
import subprocess
import sys
from pathlib import Path

src_root = Path(sys.argv[1])
kt = next(src_root.rglob('data/platform/PlatformDefinitions.kt'))
text = kt.read_text()

defs = {}
for m in re.finditer(r'PlatformDef\(\s*"([^"]+)"\s*,\s*"[^"]*"\s*,\s*"[^"]*"\s*,\s*setOf\(([^)]*)\)', text):
    defs[m.group(1)] = sorted(set(re.findall(r'"([^"]+)"', m.group(2))))

aliases = {}
block = re.search(r'slugAliases[^=]*=\s*mapOf\((.*?)\n\s*\)', text, re.S)
for a, b in re.findall(r'"([^"]+)"\s+to\s+"([^"]+)"', block.group(1) if block else ''):
    aliases[a] = b

try:
    rev = subprocess.run(['git', '-C', str(kt.parent), 'log', '-1', '--format=%h'],
                         capture_output=True, text=True).stdout.strip()
except OSError:
    rev = ''

out = ['"""File extensions each platform\'s games come in, from Argosy.',
       '',
       f'Generated by scripts/gen_platform_extensions.py from argosy-launcher {rev or "?"}',
       '(PlatformDefinitions.kt). Do not edit by hand; regenerate.',
       '"""',
       '',
       'EXTENSIONS = {']
out += [f'    {slug!r}: frozenset({exts!r}),' for slug, exts in sorted(defs.items())]
out += ['}', '', 'ALIASES = {']
out += [f'    {a!r}: {b!r},' for a, b in sorted(aliases.items())]
out += ['}', '', '',
        'def extensions_for(slug):',
        '    """Dotted extensions a platform\'s games use, or None when unknown."""',
        "    s = str(slug or '').lower()",
        '    exts = EXTENSIONS.get(ALIASES.get(s, s))',
        "    return frozenset('.' + e for e in exts) if exts else None",
        '']
dest = Path(__file__).resolve().parents[1] / 'engine/romm_sync_engine/platform_extensions.py'
dest.write_text('\n'.join(out))
print(f'{dest}: {len(defs)} platforms, {len(aliases)} aliases')
