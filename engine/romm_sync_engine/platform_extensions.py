def extensions_for(slug):
    """Dotted extensions a platform's games use, or None when unknown."""
    s = str(slug or '').lower()
    exts = EXTENSIONS.get(ALIASES.get(s, s))
    return frozenset('.' + e for e in exts) if exts else None
